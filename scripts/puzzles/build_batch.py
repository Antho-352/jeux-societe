#!/usr/bin/env python3
"""Build the first puzzle batch: PDFs, 600x600 covers and content entries.

    python3 -I scripts/puzzles/build_batch.py [--only maze,word-search,bingo,sudoku]

Writes public/pdf/puzzles/<type>/<slug>.pdf, public/img/puzzles/<slug>.png and
src/content/puzzles/<slug>.md. Entries whose body starts with <!-- hand-edited -->
and that were not produced by this script are left alone. Deterministic (fixed seeds).
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # python3 -I drops the script dir
import bingo  # noqa: E402
import mazes  # noqa: E402
import sudoku  # noqa: E402
import word_search  # noqa: E402
from batch_items import BINGO, DATE, MAZES, SHAPE_DESC, SUDOKU, WORD_SEARCHES  # noqa: E402
from common import IMG_ROOT, PDF_ROOT, ROOT, pdf_pages, render_cover, size_mb  # noqa: E402

CONTENT = ROOT / "src" / "content" / "puzzles"
MARK = "<!-- generated by scripts/puzzles/build_batch.py -->"
PRINT_LINE = "- Black and white, US Letter with 18 mm margins, so it also prints on A4 at 100 % scale."
REPORT = []


def q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def write_entry(item, type_, folder, pages, grid, count, body_pdf, difficulty=None, age=None):
    slug = item["slug"]
    pdf = PDF_ROOT / folder / f"{slug}.pdf"
    assert pdf_pages(pdf) == pages, (slug, pdf_pages(pdf), pages)
    fm = [
        "---",
        f"title: {q(item['title'])}",
        f"type: {q(type_)}",
        f"summary: {q(item['summary'])}",
    ]
    if difficulty:
        fm.append(f"difficulty: {q(difficulty)}")
    if age:
        fm.append(f"age_band: {q(age)}")
    fm += [
        f"themes: {json.dumps(item['themes'])}",
        f"occasions: {json.dumps(item.get('occasions', []))}",
        f"pages: {pages}",
        'paper: "both"',
        'colour: "bw"',
        "answers_included: true",
    ]
    if count:
        fm.append(f"count: {count}")
    if grid:
        fm.append(f"grid: {q(grid)}")
    fm += [
        f"download_url: {q(f'/pdf/puzzles/{folder}/{slug}.pdf')}",
        f"download_size_mb: {max(0.01, size_mb(pdf))}",
        f"cover: {q(f'/img/puzzles/{slug}.png')}",
        'licence: "CC BY-NC 4.0"',
        'status: "published"',
        f"date_added: {q(DATE)}",
        f"seo_title: {q(item['seo'])}",
        "---",
    ]
    about = {"maze": "About this maze", "word-search": "About this word search", "bingo": "About these bingo cards",
             "sudoku": "About this sudoku book"}[type_]
    body = [
        "<!-- hand-edited -->",
        MARK,
        f"## {about}",
        "",
        item["intro"],
        "",
        "## What's in the PDF",
        "",
        *body_pdf,
        PRINT_LINE,
        "",
        f"**Tip:** {item['tip']}",
        "",
    ]
    path = CONTENT / f"{slug}.md"
    if path.exists() and MARK not in path.read_text():
        raise SystemExit(f"refusing to overwrite {path}: not produced by this script")
    path.write_text("\n".join(fm) + "\n" + "\n".join(body))
    words = len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’.,×–-]*", "\n".join(body[2:]).replace("#", "")))
    REPORT.append(dict(slug=slug, type=type_, pages=pages, kb=round(os.path.getsize(pdf) / 1024, 1), words=words,
                       summary=len(item["summary"]), seo=len(item["seo"])))
    render_cover(pdf, IMG_ROOT / f"{slug}.png")


def build_mazes():
    for it in MAZES:
        g = dict(it["gen"])
        style = g.pop("style", "square")
        start, end = g.pop("start_label", "Start"), g.pop("end_label", "Finish")
        m = mazes.generate(g.pop("seed"), it["difficulty"], g.pop("shape"), g.pop("size", None), g.pop("aspect", 1.0),
                           g.pop("entry", "top-bottom"))
        assert not g, g
        out = PDF_ROOT / "mazes" / f"{it['slug']}.pdf"
        mazes.render_pdf(m, out, it["title"], it["difficulty"], style, start, end)
        shape = SHAPE_DESC[it["gen"]["shape"]]
        lines = [
            f"- Page 1: the {shape} maze ({m.cols} × {m.rows} grid, {len(m.cells)} cells), with {start} and {end} marked by arrows.",
            f"- Page 2: the solution, a red path {len(m.solution)} cells long.",
        ]
        write_entry(it, "maze", "mazes", 2, f"{m.cols}×{m.rows}", 1, lines, it["difficulty"], it["age"])


def build_word_searches():
    for it in WORD_SEARCHES:
        words = word_search.THEMES[it["theme"]]
        grid, placements = word_search.generate(words, it["difficulty"], it["seed"])
        out = PDF_ROOT / "word-search" / f"{it['slug']}.pdf"
        word_search.render_pdf(grid, placements, words, out, it["title"], it["difficulty"])
        n = len(grid)
        rule = {"easy": "words read left to right or top to bottom",
                "medium": "words run across, down and diagonally, never backwards",
                "hard": "words run in all eight directions, backwards included"}[it["difficulty"]]
        lines = [
            f"- Page 1: the {n} × {n} grid ({rule}) and the list of {len(words)} words to find.",
            "- Page 2: the answer key, with every word highlighted.",
        ]
        write_entry(it, "word-search", "word-search", 2, f"{n}×{n}", 1, lines, it["difficulty"], it["age"])


def build_bingo():
    for it in BINGO:
        out = PDF_ROOT / "bingo" / f"{it['slug']}.pdf"
        if it["mode"] == "numbers":
            pages = bingo.render_numbers(out, it["title"], 20, it["seed"])
            lines = [f"- Pages 1–{pages - 1}: 20 unique 5 × 5 cards, two per page, numbered, with a FREE centre square.",
                     f"- Page {pages}: the call sheet (1 to 75 by column), short rules and four winning patterns."]
            grid, count = "5×5", 20
        elif it["mode"] == "words":
            pages = bingo.render_words(out, it["title"], it["theme"], 20, it["seed"])
            n = len(bingo.THEMES[it["theme"]])
            lines = [f"- Pages 1–{pages - 1}: 20 unique 5 × 5 cards, two per page, numbered, with a FREE centre square.",
                     f"- Page {pages}: {n} calling cards to cut out, one per word (they double as the answer list)."]
            grid, count = "5×5", 20
        else:
            pages = bingo.render_blank(out, it["title"], it["size"])
            s = it["size"]
            small = 2 if s >= 4 else 4
            lines = [f"- Page 1: one large blank {s} × {s} card{' with a FREE centre square' if s == 5 else ''}, with lines for the theme and a name.",
                     f"- Page 2: {small} smaller blank {s} × {s} cards to cut apart."]
            grid, count = f"{s}×{s}", None
        write_entry(it, "bingo", "bingo", pages, grid, count, lines, None, it["age"])


def build_sudoku():
    for it in SUDOKU:
        out = PDF_ROOT / "sudoku" / f"{it['slug']}.pdf"
        total, pages, lo, hi = sudoku.render_book(out, it["title"], it["level"], it["pages"], it["seed"])
        br, bc, _, per, _, _ = sudoku.DIFFICULTY[it["level"]]
        n = br * bc
        clues = f"{lo} clues each" if lo == hi else f"{lo} to {hi} clues each"
        lines = [f"- Pages 1–{it['pages']}: {total} {n} × {n} puzzles, {per} per page ({clues}), every one with a unique solution.",
                 f"- Pages {it['pages'] + 1}–{pages}: all the solutions, with the given numbers in bold."]
        print(f"  {it['slug']}: clues {lo}-{hi}")
        write_entry(it, "sudoku", "sudoku", pages, f"{n}×{n}", total, lines, it["difficulty"], it["age"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="maze,word-search,bingo,sudoku")
    a = ap.parse_args()
    todo = a.only.split(",")
    if "maze" in todo:
        build_mazes()
    if "word-search" in todo:
        build_word_searches()
    if "bingo" in todo:
        build_bingo()
    if "sudoku" in todo:
        build_sudoku()
    for r in REPORT:
        flags = []
        if not 80 <= r["words"] <= 150:
            flags.append(f"WORDS {r['words']}")
        if r["summary"] > 220:
            flags.append("SUMMARY>220")
        if r["seo"] > 60:
            flags.append(f"SEO {r['seo']}")
        if r["kb"] > 400:
            flags.append("SIZE>400KB")
        print(f"{r['type']:12} {r['slug']:42} {r['pages']:3}p {r['kb']:7.1f} KB {r['words']:4}w  {' '.join(flags)}")


if __name__ == "__main__":
    main()
